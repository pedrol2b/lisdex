"""Generates the menu bar molecule SVGs (ADR 0011) from the lisdexamfetamine skeletal formula.

SMILES C[C@@H](Cc1ccccc1)NC(=O)[C@@H](N)CCCCN, standard horizontal depiction (PubChem-style):
phenyl -> CH2 -> CH (methyl down) -> NH -> C (=O down) -> C-alpha (NH2 up) -> (CH2)4 -> NH2.
Bond length 1, every angle 120 deg, math coordinates (y up). Labels, wedges and double bonds
are omitted, as in the Figma identity.

  B / minimal  (default): everything up to the C-alpha and its NH2 (14 heavy atoms).
  A / faithful (option):  the complete molecule (19 heavy atoms).

Usage: python3 -I scripts/lisdexamfetamine-skeleton.py assets/menubar
"""

import math
import sys

HEIGHT = 18  # pt (macOS scales taller status images down to ~18 pt)
STROKES = {"inactive": (1.6, False), "active": (2.0, True)}  # pt, phenyl filled?
COS30, SIN30 = math.cos(math.radians(30)), 0.5

RING = [(math.cos(math.radians(a)), math.sin(math.radians(a))) for a in (30, 90, 150, 210, 270, 330)]


def molecule(full):
    """Atoms (name -> point) and bonds of the chain; the phenyl ring is drawn separately."""
    chain = ["C7", "C8", "N10", "C11", "C13"] + (["C15", "C16", "C17", "C18", "N19"] if full else [])
    atoms = {"ipso": RING[0]}
    x, y = RING[0]
    rising = True
    for name in chain:
        x, y = x + COS30, y + (SIN30 if rising else -SIN30)
        atoms[name] = (x, y)
        rising = not rising
    atoms["C9"] = (atoms["C8"][0], atoms["C8"][1] - 1)  # methyl, down
    atoms["O12"] = (atoms["C11"][0], atoms["C11"][1] - 1)  # carbonyl oxygen, down
    atoms["N14"] = (atoms["C13"][0], atoms["C13"][1] + 1)  # alpha amine, up
    backbone = ["ipso"] + chain
    bonds = list(zip(backbone, backbone[1:])) + [("C8", "C9"), ("C11", "O12"), ("C13", "N14")]
    return atoms, bonds


def check(atoms, bonds, heavy_atoms):
    assert len(atoms) - 1 + len(RING) == heavy_atoms, len(atoms)
    neighbours = {}
    for a, b in bonds:
        neighbours.setdefault(a, []).append(b)
        neighbours.setdefault(b, []).append(a)
    for centre, around in neighbours.items():
        for i, first in enumerate(around):
            for second in around[i + 1 :]:
                (ax, ay), (bx, by), (cx, cy) = atoms[first], atoms[centre], atoms[second]
                u, v = (ax - bx, ay - by), (cx - bx, cy - by)
                cos = (u[0] * v[0] + u[1] * v[1]) / math.hypot(*u) / math.hypot(*v)
                assert round(math.degrees(math.acos(cos))) == 120, (centre, first, second)


def frame(atoms, stroke):
    """Stroke-inclusive bounding box in bond units, and the pt-per-bond scale."""
    points = RING + list(atoms.values())
    xs, ys = [p[0] for p in points], [p[1] for p in points]
    # Total height including half a stroke on each side: span * scale + stroke == HEIGHT.
    scale = (HEIGHT - stroke) / (max(ys) - min(ys))
    pad = stroke / scale / 2
    box = (min(xs) - pad, -(max(ys) + pad), max(xs) - min(xs) + 2 * pad, max(ys) - min(ys) + 2 * pad)
    return box, HEIGHT / box[3]


def svg(atoms, bonds, box, scale, stroke, filled, label):
    point = lambda p: f"{p[0]:.4f} {-p[1]:.4f}"
    attrs = (
        f'stroke="currentColor" stroke-width="{stroke / scale:.4f}" '
        'stroke-linecap="round" stroke-linejoin="round"'
    )
    ring = "M" + "L".join(point(p) for p in RING) + "Z"
    chain = " ".join(f"M{point(atoms[a])}L{point(atoms[b])}" for a, b in bonds)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{box[2] * scale:.2f}" height="{HEIGHT}" '
        f'viewBox="{" ".join(f"{v:.4f}" for v in box)}" fill="none">\n'
        f"  <!-- Lisdexamfetamine skeletal formula ({label}). Generated by "
        f"scripts/lisdexamfetamine-skeleton.py; edit the script, not this file. -->\n"
        f'  <path id="phenyl" d="{ring}" fill="{"currentColor" if filled else "none"}" {attrs}/>\n'
        f'  <path id="chain" d="{chain}" {attrs}/>\n'
        "</svg>\n"
    )


def main(out):
    variants = {"b": (False, 14, "fragment, 14 heavy atoms"), "a": (True, 19, "complete, 19 heavy atoms")}
    for letter, (full, heavy, label) in variants.items():
        atoms, bonds = molecule(full)
        check(atoms, bonds, heavy)
        # Both states share the thicker (active) frame so the icon never shifts when toggled.
        box, scale = frame(atoms, STROKES["active"][0])
        for state, (stroke, filled) in STROKES.items():
            with open(f"{out}/status-{letter}-{state}.svg", "w") as handle:
                handle.write(svg(atoms, bonds, box, scale, stroke, filled, label))
        print(f"status-{letter}: {label}, angles 120 deg, {box[2] * scale:.2f} x {HEIGHT} pt")


if __name__ == "__main__":
    main(sys.argv[1])
